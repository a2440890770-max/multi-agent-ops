import { readFile, writeFile } from 'node:fs/promises';
import { format } from 'prettier';
import { endpoints, getOpenApiDocument } from '../shared/src/index.ts';

const spec = getOpenApiDocument();
const schemas = spec.components.schemas;
function tsType(s) {
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  if (Array.isArray(s.type)) return s.type.map((t) => tsType({ ...s, type: t })).join(' | ');
  if (s.type === 'null') return 'null';
  if (s.type === 'integer' || s.type === 'number') return 'number';
  if (s.type === 'boolean') return 'boolean';
  if (s.type === 'array') return `(${tsType(s.items)})[]`;
  if (s.type === 'object')
    return `{ ${Object.entries(s.properties ?? {})
      .map(
        ([name, property]) =>
          `${JSON.stringify(name)}${s.required?.includes(name) ? '' : '?'}: ${tsType(property)};`,
      )
      .join(' ')} }`;
  return 'string';
}
let requestTypes =
  '// Generated by npm run contract:generate. Do not edit.\nimport type { ResponseModels } from "../responses.js";\n';
for (const [name, pick] of [
  ['OperationBodies', (e) => (e.body ? tsType(e.body) : 'undefined')],
  ['OperationQueries', (e) => (e.query ? tsType(e.query) : 'undefined')],
  [
    'OperationParams',
    (e) =>
      e.path.includes(':')
        ? `{ ${[...e.path.matchAll(/:([A-Za-z]+)/g)].map((m) => `${m[1]}: string;`).join(' ')} }`
        : 'Record<string, never>',
  ],
  ['OperationResponses', (e) => `ResponseModels[${JSON.stringify(e.response)}]`],
]) {
  requestTypes += `export interface ${name} { ${endpoints.map((e) => `${e.operationId}: ${pick(e)};`).join('\n')} }\n`;
}
requestTypes += 'export type OperationId = keyof OperationResponses;\n';
const requestTarget = new URL('../shared/src/generated/request-models.ts', import.meta.url);
const requestOutput = await format(requestTypes, {
  parser: 'typescript',
  singleQuote: true,
  printWidth: 100,
  trailingComma: 'all',
});
function type(s) {
  if (s.$ref) return s.$ref.split('/').at(-1);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' / ');
  if (s.anyOf) return s.anyOf.map(type).join(' / ');
  if (s.type === 'array') return `${type(s.items)}[]`;
  return Array.isArray(s.type) ? s.type.join(' / ') : (s.type ?? 'object');
}
function rules(s) {
  return (
    [
      ['minLength', '最短'],
      ['maxLength', '最长'],
      ['minimum', '最小'],
      ['maximum', '最大'],
      ['minItems', '最少项'],
      ['maxItems', '最多项'],
      ['format', '格式'],
      ['pattern', '匹配'],
    ]
      .filter(([key]) => s[key] !== undefined)
      .map(([key, label]) => `${label} ${s[key]}`)
      .join('；') || '见业务前置条件'
  );
}
function fields(s, prefix = '') {
  return Object.entries(s?.properties ?? {}).flatMap(([name, value]) => {
    const row = `| ${prefix}${name} | ${s.required?.includes(name) ? '是' : '否'} | ${type(value)} | ${rules(value).replaceAll('|', '\\|')} |`;
    return [row, ...(value.items?.properties ? fields(value.items, `${prefix}${name}[].`) : [])];
  });
}
let output =
  '# 接口逐项参考（生成文件）\n\n由 shared 契约生成；运行 `npm run contract:generate` 更新。通用权限、错误、超时与审计规则见 [接口契约说明](api-contract.md)。D3 已实现登录、当前身份、退出及业务接口会话/角色/写入 Origin/CSRF 校验；通过权限检查后，其他业务处理仍为 501 占位。\n\n';
output += '| 操作 ID | 方法与路径 | 用途 |\n| --- | --- | --- |\n';
for (const e of endpoints)
  output += `| ${e.operationId} | ${e.method} /api/v1${e.path} | [${e.summary}](#${e.operationId.toLowerCase()}) |\n`;
for (const e of endpoints) {
  output += `\n## ${e.operationId}\n\n\`${e.method} /api/v1${e.path}\` — ${e.summary}。\n\n`;
  output += `权限：${e.roles.length ? e.roles.join(' / ') : '无需已登录会话'}。\n\n前置条件与业务校验：${e.conditions}\n\n`;
  const pathFields = [...e.path.matchAll(/:([A-Za-z]+)/g)].map((m) => m[1]);
  if (pathFields.length)
    output += `路径字段：${pathFields.map((name) => `\`${name}\``).join('、')} 均必填，为 1—128 位不透明 ID，仅字母、数字、下划线、连字符；逐级校验对象同属团队/任务。\n\n`;
  if (e.method !== 'GET')
    output += `请求头：${e.operationId === 'logout' ? 'Idempotency-Key 可选' : 'Idempotency-Key 必填，16—128 字符'}${e.operationId === 'login' ? '；登录校验 Origin' : '；X-CSRF-Token 必填（已过期退出会话例外）'}。\n\n`;
  for (const [label, s] of [
    ['查询参数', e.query],
    ['JSON 请求体', e.body],
  ]) {
    if (s)
      output += `${label}（未列字段拒绝）：\n\n| 字段 | 必填 | 类型 | 校验 |\n| --- | --- | --- | --- |\n${fields(s).join('\n')}\n\n`;
  }
  if (!e.body && e.method !== 'GET') output += '无请求体。\n\n';
  output += `成功：HTTP ${e.success}${e.operationId === 'approveContent' ? '（已有有效批准时 200）' : ''}，\`{ data: ${e.response}, meta: { requestId, replayed } }\`。data 字段：\n\n| 字段 | 类型 | 含义 |\n| --- | --- | --- |\n`;
  for (const [name, s] of Object.entries(schemas[e.response].properties))
    output += `| ${name} | ${type(s)} | ${name === 'items' ? '当前分页结果' : name === 'nextCursor' ? '下一页不透明游标，null 表示结束' : '同名共享对象字段，见核心对象设计与 OpenAPI 完整结构'} |\n`;
  output += `\n重复与并发：${e.repetition}\n\n超时与失败：遵循 [统一故障协议](api-contract.md#故障与冲突协议)；发布相关写入不自动重发。错误体始终为 ApiError；所有未满足前置条件的操作保持业务原状态。\n\n转换：${e.transitions.length ? e.transitions.join('、') : '无业务状态转换'}。审计：${e.audit}。验收：${e.ac.join('、')}（关联设计，不表示已验收）。\n`;
}
const target = new URL('../docs/design/api-reference.md', import.meta.url);
const formatted = await format(output, {
  parser: 'markdown',
  printWidth: 100,
  proseWrap: 'preserve',
});
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== formatted)
    throw new Error('API reference is stale. Run npm run contract:generate.');
  if ((await readFile(requestTarget, 'utf8')) !== requestOutput)
    throw new Error('Request types are stale. Run npm run contract:generate.');
} else {
  await writeFile(target, formatted);
  await writeFile(requestTarget, requestOutput);
}
