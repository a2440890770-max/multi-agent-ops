import ts from 'typescript';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const root = fileURLToPath(new URL('../', import.meta.url));
const file = `${root}shared/src/responses.ts`;
const program = ts.createProgram([file], { strict: true, target: ts.ScriptTarget.ES2023 });
const checker = program.getTypeChecker();
const source = program.getSourceFile(file);
const models = source.statements.find(
  (s) => ts.isInterfaceDeclaration(s) && s.name.text === 'ResponseModels',
);
if (!models) throw new Error('ResponseModels missing');
const schemas = {};
function schema(type, inline = false) {
  if (type.flags & ts.TypeFlags.StringLiteral) return { type: 'string', enum: [type.value] };
  if (type.flags & ts.TypeFlags.NumberLiteral) return { type: 'number', enum: [type.value] };
  if (type.flags & ts.TypeFlags.BooleanLiteral)
    return { type: 'boolean', enum: [type.intrinsicName === 'true'] };
  if (type.flags & ts.TypeFlags.String) return { type: 'string' };
  if (type.flags & ts.TypeFlags.Number) return { type: 'number' };
  if (type.flags & ts.TypeFlags.Boolean) return { type: 'boolean' };
  if (type.flags & ts.TypeFlags.Null) return { type: 'null' };
  if (type.isUnion()) {
    const variants = type.types.filter((t) => !(t.flags & ts.TypeFlags.Undefined)).map(schema);
    if (variants.length === 1) return variants[0];
    if (variants.every((s) => s.type === 'boolean')) return { type: 'boolean' };
    if (variants.every((s) => s.enum && s.type === variants[0].type))
      return { type: variants[0].type, enum: variants.flatMap((s) => s.enum) };
    return { anyOf: variants };
  }
  if (checker.isArrayType(type))
    return { type: 'array', items: schema(checker.getTypeArguments(type)[0]) };
  if (type.flags & ts.TypeFlags.Object) {
    const symbol = type.aliasSymbol ?? type.symbol;
    if (
      !inline &&
      symbol &&
      !symbol.name.startsWith('__') &&
      symbol.declarations?.some((d) => d.getSourceFile().fileName.startsWith(`${root}shared/`))
    ) {
      const name = checker.typeToString(type).replace(/[^A-Za-z0-9_]/g, '_');
      if (!schemas[name]) {
        schemas[name] = {};
        schemas[name] = schema(type, true);
      }
      return { $ref: `#/components/schemas/${name}` };
    }
    const properties = {};
    const required = [];
    for (const property of checker.getPropertiesOfType(type)) {
      properties[property.name] = schema(
        checker.getTypeOfSymbolAtLocation(property, property.valueDeclaration ?? models),
      );
      if (!(property.flags & ts.SymbolFlags.Optional)) required.push(property.name);
    }
    return { type: 'object', additionalProperties: false, properties, required };
  }
  throw new Error(`Unsupported contract type: ${checker.typeToString(type)}`);
}
for (const member of models.members)
  schemas[member.name.text] = schema(checker.getTypeAtLocation(member), true);
const output = await format(
  `// Generated by npm run contract:generate from ResponseModels. Do not edit.\nexport const responseSchemas = ${JSON.stringify(schemas)} as const;\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 100, trailingComma: 'all' },
);
const target = `${root}shared/src/generated/response-schemas.ts`;
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== output)
    throw new Error('Contract schemas are stale. Run npm run contract:generate.');
} else {
  await mkdir(`${root}shared/src/generated`, { recursive: true });
  await writeFile(target, output);
}
